package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

const S = "00000001 00000100 00001000 00001002 00010000 00010020 00100000 00100200 00100203 00100243 00100245 00100645 00100675 00200001 00203001 00243001 00245001 00645001 00675001 00675081 01000000 01002000 01002030 01002430 01002450 01006450 01006750 03001002 08100675 10000000 10020000 10020300 10024300 10024500 10064500 10067500 10067508 20000100 20300100 24300100 24500100 30010020 30010024 43001002 45001002 45001006 50010024 50010064 50010067 50810067 64500100 67500100 67508100 75001006 75081006 81006750"

func main() {
	r := bufio.NewReader(os.Stdin)
	ok := true
	for {
		h := make([]byte, 8)
		for i := 0; i < 8; i++ {
			var l string
			if _, e := fmt.Fscan(r, &l); e != nil {
				return
			}
			h[i] = l[0]
		}
		if !strings.Contains(S, string(h)) {
			ok = false
		}
		if ok {
			m := 0
			for i := 1; i < 8; i++ {
				if h[i] > h[m] {
					m = i
				}
			}
			fmt.Println(m)
		} else {
			fmt.Println("x")
		}
	}
}
